// Turns the Hairline figures in this folder into modules the CRM imports:
//   node hairline/export.mjs
// writes lib/hairline/kernel.ts (the engine, unchanged) and lib/hairline/figures.ts
// (each figure's source wrapped in a function of (HL, hairline)).
// Re-run it after editing a figure. Figures are made with the /hairline-create skill.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "lib", "hairline");
const kernelSrc = readFileSync(join(homedir(), ".claude/skills/hairline-create/kernel.js"), "utf8");

writeFileSync(
  join(out, "kernel.ts"),
  `// @ts-nocheck\n// The Hairline engine (@lucasmarkes/hairline), unchanged: see hairline/export.mjs.\n${kernelSrc.replace(/^var HL =/m, "export const HL: any =")}\n`,
);

const names = readdirSync(here).filter((f) => f.endsWith(".js")).map((f) => f.slice(0, -3)).sort();
const body = names
  .map((n) => {
    const src = readFileSync(join(here, `${n}.js`), "utf8");
    return `  ${JSON.stringify(n)}: (HL: any, hairline: (figure: any) => void) => {\n${src.replace(/^/gm, "    ")}\n  },`;
  })
  .join("\n");
writeFileSync(
  join(out, "figures.ts"),
  `// @ts-nocheck\n// Generated by hairline/export.mjs from the figures in hairline/*.js. Do not edit.\nexport const figureSources = {\n${body}\n} as const;\n\nexport type FigureName = keyof typeof figureSources;\n`,
);
console.log("exported", names.join(", "));
